#!/usr/bin/env bun
// The guard: an app holds imports and data only. UI comes from the design repo; something new is made in the
// playground first. It fails when an app (its own .contract and .forma files) defines
//   - a component other than its root (App),
//   - a style, a keyframes or a font,
//   - a raw colour (#hex, rgb(), hsl(), oklch(), light-dark(), color(), a platform colour role),
//   - a style or size of its own (any style attribute on a node, a length, a token of its own),
//   - a drawn node (text, box, row, column, image, svg, button, link, list, scroll, …): only a Screen,
//     Block or Component draws, and native text input and menus (input, textarea, select) are the platform's,
// or when a vendored copy of the design packages differs from its manifest (an edit by hand).
// A generated file (its first line says so) is checked by its generator, not here.
//
//   bun tools/ui-guard.mjs <app dir> [--json]
//
// Exit 0 when clean; 1 with one line per finding, file:line first.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const RULE = 'REFUSED by ui-guard (agent-ui-kit starter/README.md, "Guards": UI comes from the design repo; new things start in the playground)';
const GENERATED = /^\/\/ Generated by agent-ui-kit tools\//;

// Nodes an app may write: the navigation root (filling the window: width and height "100%"), a modal's host, and
// the platform's own text input and menus.
const ALLOWED_TAGS = new Set(['main', 'dialog', 'input', 'textarea', 'select', 'option', 'optgroup', 'label']);
// Attributes that are not style: identity, behaviour, accessibility, data, navigation, and event handlers (a call's
// hang up, a pointer, a key, media).
const NOT_STYLE = /^(id|testId|key|href|value|type|name|min|max|step|placeholder|autocomplete|inputmode|enterkeyhint|required|readonly|disabled|checked|selected|multiple|for|form|open|title|lang|dir|role|tabindex|autofocus|hidden|inert|aria-[\w-]+|data-[\w-]+|press|input|change|submit|close|cancel|toggle|focus|blur|keydown|keyup|navigate|navigationKey|navigationBack|navigationScroll|navigationTitle|scroll|reachend|refresh|delete|contextmenu|when|call\w+|pointer\w+|key\w+|touch\w+|drag\w*|drop|wheel|paste|copy|cut|play|playing|pause|ended|load\w*|error|timeupdate|seek\w*|volumechange|ratechange|visibilitychange|selectionchange|beforeinput|composition\w+|focusin|focusout|resize|share)$/;
const COLOUR = /#[0-9a-fA-F]{3,8}\b|\b(rgba?|hsla?|hwb|oklch|oklab|lab|lch|light-dark|color)\(|"-exact-[a-z-]*(label|color|fill|background|separator|tint|system-[a-z]+)[a-z-]*"|"(Canvas|CanvasText|ButtonText|LinkText|AccentColor|Highlight|HighlightText)"/;
const DECL = /^(style|keyframes|font)\s/;

const findings = [];
const say = (file, line, what) => findings.push({ file, line, what });

function files(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (['node_modules', 'target', 'dist', '.exact', '.git', 'vendor', 'wip'].includes(name) || name.startsWith('dist.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) files(p, out);
    else if ((name.endsWith('.contract') && !name.endsWith('.test.contract')) || name.endsWith('.forma')) out.push(p);
  }
  return out;
}

function contract(file, rel) {
  const lines = readFileSync(file, 'utf8').split('\n');
  if (GENERATED.test(lines[0] ?? '')) return;
  let components = 0;
  let inView = false;
  let viewIndent = 0;
  lines.forEach((raw, i) => {
    const n = i + 1;
    const line = raw.replace(/\s+\/\/.*$/, '').replace(/^\s*\/\/.*$/, '');
    if (!line.trim()) return;
    const top = /^\S/.test(line);
    if (top) inView = false;
    const comp = /^component (\w+)/.exec(line);
    if (comp) {
      components++;
      if (components > 1 || comp[1] !== 'App') say(rel, n, `defines a component (${comp[1]}): take it from the design repo's Screens, Blocks or Components; make a new one in the playground first`);
    }
    if (DECL.test(line)) say(rel, n, `defines a ${line.split(/\s/)[0]}: styles, keyframes and fonts live in the design repo's Theme and Components`);
    if (/^ {2}view\s*$/.test(line)) { inView = true; viewIndent = 4; return; }
    if (COLOUR.test(line.replace(/"(?:[^"\\]|\\.)*"/g, (s) => (/^"(#|-exact-|Canvas|Button|Link|Accent|Highlight)/.test(s) || /\b(rgba?|hsla?|oklch|light-dark|color)\(/.test(s) ? s : '""')))) {
      say(rel, n, 'holds a raw colour: colours are the Theme\'s tokens, named only inside the design repo');
    }
    if (!inView) return;
    const m = /^(\s*)([A-Za-z][\w-]*)(.*)$/.exec(line);
    if (!m || m[1].length < viewIndent) return;
    const [, , tag, rest] = m;
    if (['if', 'else', 'for', 'match', 'case', 'elif', 'children'].includes(tag)) return;
    if (/^[A-Z]/.test(tag)) return; // a component call: its arguments are data and actions
    if (tag.startsWith(':')) { say(rel, n, `styles a state (${tag}): states are drawn by the design repo's pieces`); return; }
    if (!ALLOWED_TAGS.has(tag)) { say(rel, n, `draws its own UI (\`${tag}\`): use a Screen, Block or Component from the design repo`); return; }
    for (const a of rest.matchAll(/(?:^|\s)([A-Za-z][\w-]*)=("100%")?/g)) {
      // The navigation root fills the window (Exact draws it at no height otherwise): that, and only that, is allowed.
      if (tag === 'main' && (a[1] === 'width' || a[1] === 'height') && a[2] === '"100%"') continue;
      if (!NOT_STYLE.test(a[1])) say(rel, n, `styles a node (\`${a[1]}\` on \`${tag}\`): sizes and looks belong to the design repo's pieces`);
    }
  });
}

function forma(file, rel) {
  const lines = readFileSync(file, 'utf8').split('\n');
  if (GENERATED.test(lines[0] ?? '')) return;
  lines.forEach((raw, i) => {
    const line = raw.replace(/\s*\/\/.*$/, '');
    const tok = /^\s{2,}([\w.-]+)(?::\s*\w+)?\s*=\s*(.+?)\s*$/.exec(line);
    if (!tok) return;
    // Only a pointer from a name the platform reads to a Theme token: `AccentColor = theme.color.accent`.
    if (!/^theme\.[\w.-]+$/.test(tok[2])) say(rel, i + 1, `defines a design value (${tok[1]} = ${tok[2]}): the Theme is the design repo's theme.json; an app may only point a platform name at a Theme token`);
  });
}

function vendor(app) {
  const manifest = join(app, 'vendor', 'MANIFEST.json');
  if (!existsSync(manifest)) return;
  const m = JSON.parse(readFileSync(manifest, 'utf8'));
  for (const [path, sum] of Object.entries(m.files ?? {})) {
    const p = join(app, 'vendor', path);
    if (!existsSync(p)) { say('vendor/MANIFEST.json', 1, `vendor/${path} is missing: run the design repo's vendor step again`); continue; }
    const got = createHash('sha256').update(readFileSync(p)).digest('hex');
    if (got !== sum) say(`vendor/${path}`, 1, 'differs from the design repo\'s copy (edited by hand): change it in the design repo, then vendor again');
  }
}

export function guard(app) {
  findings.length = 0;
  for (const f of files(app)) {
    const rel = relative(app, f);
    if (f.endsWith('.contract')) contract(f, rel);
    else forma(f, rel);
  }
  vendor(app);
  return [...findings];
}

if (import.meta.main) {
  const [app, flag] = process.argv.slice(2);
  if (!app) { console.error('usage: bun tools/ui-guard.mjs <app dir> [--json]'); process.exit(2); }
  const out = guard(app);
  if (flag === '--json') console.log(JSON.stringify(out));
  else if (out.length) {
    console.error(`${RULE}: ${out.length} finding${out.length === 1 ? '' : 's'} in ${app}.`);
    for (const f of out) console.error(`  ${f.file}:${f.line}: ${f.what}`);
  } else console.log(`ui-guard: ${app}: imports and data only`);
  process.exit(out.length ? 1 : 0);
}
